import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entitiesDir = path.join(root, 'base44', 'entities');
const output = path.join(root, 'base44', 'shared', 'generated', 'disasterRecoveryEntityCatalog.ts');
const check = process.argv.includes('--check');

const names = fs.readdirSync(entitiesDir)
  .filter((name) => name.endsWith('.jsonc'))
  .map((name) => name.slice(0, -'.jsonc'.length))
  .sort((a, b) => a.localeCompare(b, 'en'));

const source = `// Generated by scripts/generate-dr-entity-catalog.mjs. Do not edit manually.\n` +
  `export const DISASTER_RECOVERY_ENTITY_CATALOG = Object.freeze(${JSON.stringify(names, null, 2)} as const);\n` +
  `export const DISASTER_RECOVERY_ENTITY_CATALOG_VERSION = 'dr-entity-catalog-v1:${names.length}';\n`;

if (check) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
  if (current !== source) {
    console.error('Disaster-recovery entity catalog is stale. Run npm run dr:catalog:generate.');
    process.exit(1);
  }
  console.log(`Disaster-recovery entity catalog current (${names.length} entities).`);
} else {
  fs.mkdirSync(path.dirname(output), { recursive:true });
  fs.writeFileSync(output, source);
  console.log(`Generated ${path.relative(root, output)} (${names.length} entities).`);
}
