#!/usr/bin/env node
// AUDIT 2026-08-18 — shared backend modules imported `../../config/*.json`
// directly. The Base44 function bundler cannot reach outside a function's own
// tree, so every function transitively importing those modules FAILED to
// deploy and silently kept serving stale code. The repo already had the
// correct pattern for this exact problem (base44/shared/generated/*.ts), so
// this generator emits the same kind of frozen TS artifact from the canonical
// JSON and a --check mode proves the artifact never drifts from it.
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const ARTIFACTS = [
  {
    out: "base44/shared/generated/researchKnowledgeConfig.ts",
    sources: [
      { name: "RESEARCH_KNOWLEDGE_CATALOG", file: "config/intelligence/research-knowledge.v1.json" },
      { name: "RESEARCH_KNOWLEDGE_CONFLICTS", file: "config/intelligence/research-conflicts.v1.json" },
    ],
  },
  {
    out: "base44/shared/generated/growthPathDefaults.ts",
    sources: [
      { name: "GROWTH_PATH_DEFAULTS", file: "config/growth-path-defaults.json" },
    ],
  },
];

function render(artifact) {
  const header = [
    `// GENERATED by scripts/generate-shared-config-artifacts.mjs — DO NOT EDIT.`,
    `// Canonical source${artifact.sources.length > 1 ? "s" : ""}: ${artifact.sources.map((s) => s.file).join(", ")}`,
    `// Exists because the Base44 function bundler cannot import JSON from outside`,
    `// a function's own tree; drift is gated by \`npm run shared-config:check\`.`,
    ``,
  ].join("\n");
  const body = artifact.sources
    .map((source) => {
      const json = JSON.parse(fs.readFileSync(source.file, "utf8"));
      return `export const ${source.name} = Object.freeze(${JSON.stringify(json, null, 2)} as const);\n`;
    })
    .join("\n");
  return `${header}${body}`;
}

const checkMode = process.argv.includes("--check");
let failed = false;

for (const artifact of ARTIFACTS) {
  const expected = render(artifact);
  if (checkMode) {
    const actual = fs.existsSync(artifact.out) ? fs.readFileSync(artifact.out, "utf8") : null;
    if (actual !== expected) {
      console.error(`shared-config:check FAIL — artifact drifted from canonical JSON: ${artifact.out}`);
      failed = true;
    }
    continue;
  }
  fs.mkdirSync(path.dirname(artifact.out), { recursive: true });
  fs.writeFileSync(artifact.out, expected);
}

if (failed) process.exit(1);
console.log(
  `shared-config:${checkMode ? "check" : "generate"} PASS — ${ARTIFACTS.length} generated artifacts, ${
    ARTIFACTS.reduce((total, a) => total + a.sources.length, 0)
  } canonical JSON sources.`,
);